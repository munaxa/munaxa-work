#!/usr/bin/env node
/**
 * Migration safety gate — MW-008, prisma/README.md.
 *
 * The SQL in `prisma/migrations/<timestamp>_<name>/migration.sql` is the authoritative database
 * model. `prisma/schema.prisma` cannot express the overlap exclusions, partial indexes and
 * row-level security that model relies on, so a migration generated from it (`prisma migrate dev`)
 * drops them. This gate refuses the ways that happens:
 *
 * - **A migration that looks generated.** Prisma's step markers (`-- CreateTable`), its warnings
 *   block, its default `ON UPDATE CASCADE` and its `<table>_pkey` constraint names. A hand-written
 *   migration opens with a prose comment saying what it does and why.
 * - **A merged migration that changed.** `prisma migrate deploy` records a checksum per applied
 *   migration; editing or deleting one that already ran anywhere breaks every later deploy there.
 * - **A new migration that sorts before the last merged one** is reported as a warning, not a
 *   failure: `migrate deploy` still applies it, but databases that already ran the later one apply
 *   the two in a different order from a fresh database, so the author should confirm they commute.
 * - **A package script that bypasses the SQL.** `prisma migrate dev` and `prisma db push` are
 *   forbidden in every script; `prisma migrate reset` only behind scripts/db-reset-guard.mjs.
 *
 * The base is `MIGRATION_BASE_REF` (CI passes the pull request's base SHA), else `origin/main`.
 * Dependency-free: it runs on a bare checkout, before `pnpm install`. It needs git history for
 * the base (a checkout with `fetch-depth: 0`).
 *
 * Usage: node scripts/check-migration-safety.mjs
 */

import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const MIGRATIONS_DIR = 'prisma/migrations';
const MIGRATION_NAME = /^\d{14}_[a-z0-9]+(_[a-z0-9]+)*$/;
const RESET_GUARD = 'scripts/db-reset-guard.mjs';

/** One comment line naming a schema step, as `prisma migrate dev` writes before every statement. */
const PRISMA_STEP_MARKER = /^--\s+(Create|Alter|Drop|Rename|Add|Redefine)[A-Z][A-Za-z]*\s*$/m;
/** The block Prisma puts first when a generated migration may lose data. */
const PRISMA_WARNINGS = /^\/\*\s*\n\s*Warnings:/m;
/** Prisma's referential default; every hand-written foreign key here leaves ON UPDATE alone. */
const PRISMA_ON_UPDATE =
  /\bON DELETE (RESTRICT|CASCADE|SET NULL|SET DEFAULT|NO ACTION) ON UPDATE CASCADE\b/i;
/** Prisma names a primary key `<table>_pkey`; the migrations here name theirs or leave it unnamed. */
const PRISMA_PKEY = /CONSTRAINT\s+"[A-Za-z0-9_]+_pkey"\s+PRIMARY KEY/i;

/**
 * Reasons a migration's SQL looks generated by Prisma rather than written by hand. Empty when it
 * looks hand-written.
 */
export function findGeneratedSignals(sql) {
  const reasons = [];
  const marker = sql.match(PRISMA_STEP_MARKER);
  if (marker) reasons.push(`carries Prisma's step marker "${marker[0].trim()}"`);
  if (PRISMA_WARNINGS.test(sql)) reasons.push("opens with Prisma's generated Warnings block");
  if (PRISMA_ON_UPDATE.test(sql)) reasons.push("uses Prisma's default ON UPDATE CASCADE");
  if (PRISMA_PKEY.test(sql)) reasons.push('names a primary key "<table>_pkey" as Prisma does');
  const first = sql.split('\n').find((line) => line.trim() !== '');
  if (first === undefined) {
    reasons.push('is empty');
  } else if (!/^--\s*\S/.test(first) || PRISMA_STEP_MARKER.test(first)) {
    reasons.push('does not open with a hand-written comment saying what it does and why');
  }
  return reasons;
}

/**
 * Judges the changes under prisma/migrations between the base and HEAD.
 *
 * @param {{status: string, path: string}[]} changes  `git diff --name-status --no-renames` rows
 * @param {string[]} baseMigrations  migration directory names present at the base
 * @returns {{errors: string[], warnings: string[], added: string[]}} added: new migration.sql paths
 */
export function judgeMigrationChanges(changes, baseMigrations) {
  const errors = [];
  const warnings = [];
  const added = [];
  const merged = new Set(baseMigrations);
  const latest = [...baseMigrations].sort().at(-1) ?? '';
  for (const { status, path } of changes) {
    const relative = path.slice(MIGRATIONS_DIR.length + 1);
    const directory = relative.includes('/') ? relative.split('/')[0] : '';
    if (status !== 'A' || merged.has(directory) || directory === '') {
      const verb = status === 'D' ? 'deletes' : status === 'A' ? 'adds a file to' : 'modifies';
      const what = directory === '' ? relative : `merged migration ${directory}`;
      errors.push(
        `${path}: this change ${verb} ${what}. A merged migration is immutable; write a new one.`,
      );
      continue;
    }
    if (!MIGRATION_NAME.test(directory)) {
      errors.push(`${path}: a migration directory is <14-digit timestamp>_<snake_case_name>.`);
      continue;
    }
    if (directory <= latest) {
      warnings.push(
        `${path}: ${directory} sorts before the latest merged migration ${latest}. Databases that ` +
          'already ran that one apply them in the other order; confirm the two commute.',
      );
    }
    if (relative === `${directory}/migration.sql`) {
      added.push(path);
    } else {
      errors.push(`${path}: a migration directory holds only migration.sql.`);
    }
  }
  return { errors, warnings, added };
}

/**
 * The one shape a script that resets the database may take: the guard, `&&`, then the reset with
 * an optional schema path and harmless flags, and nothing else. An allow-list rather than a list
 * of bypasses, because a shell offers too many ways (`||`, `;`, `&`, a newline, a substitution, an
 * environment assignment, a `cd`, quoting, escaping) to run a reset the guard refused.
 */
const ALLOWED_RESET =
  /^node scripts\/db-reset-guard\.mjs && (pnpm --filter @work\/api exec )?prisma migrate reset( --schema [A-Za-z0-9_./-]+)?( --(skip-seed|skip-generate))*$/;

/** What a shell would make of quoting and escaping, for detection only: `'re'\set` reads `reset`. */
const unquoted = (command) => command.replace(/['"\\]/g, '').toLowerCase();

/** Package scripts that would let Prisma write the database model instead of the SQL. */
export function findForbiddenScripts(manifestPath, manifest) {
  const errors = [];
  for (const [name, command] of Object.entries(manifest.scripts ?? {})) {
    const where = `${manifestPath} script "${name}"`;
    const plain = unquoted(command);
    if (/db\s*push/.test(plain)) {
      errors.push(`${where} runs \`prisma db push\`; it rewrites the schema without a migration.`);
      continue;
    }
    if (!/migrate/.test(plain) || !/reset|push|dev/.test(plain)) continue;
    if (!ALLOWED_RESET.test(command)) {
      errors.push(
        `${where} can run \`prisma migrate dev\`, \`push\` or \`reset\` outside the one allowed ` +
          `form: \`node ${RESET_GUARD} && [pnpm --filter @work/api exec ]prisma migrate reset ` +
          '[--schema <path>] [--skip-seed] [--skip-generate]`, with nothing before or after it.',
      );
    }
  }
  return errors;
}

const git = (...args) => execFileSync('git', args, { encoding: 'utf8' });

/**
 * The refs to take the base from. A base the caller named (CI passes the pull request's base SHA)
 * is the only candidate: if it cannot be resolved the gate fails rather than quietly comparing
 * with something else. Only when none is named (or git reports the all-zero SHA of a new ref) is
 * `origin/main` used.
 */
export function baseCandidates(named) {
  const value = (named ?? '').trim();
  return value === '' || /^0+$/.test(value) ? ['origin/main'] : [value];
}

function resolveBase() {
  const [ref] = baseCandidates(process.env.MIGRATION_BASE_REF);
  try {
    return execFileSync('git', ['merge-base', ref, 'HEAD'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    process.stderr.write(
      `::error::Migration safety cannot resolve the base ${ref} in this clone, so it refuses ` +
        'rather than compare with anything else. Check out with full history (fetch-depth: 0) ' +
        'or set MIGRATION_BASE_REF to a ref the clone has.\n',
    );
    process.exit(1);
  }
}

function packageManifests() {
  const paths = ['package.json'];
  for (const root of ['apps', 'packages']) {
    if (!existsSync(root)) continue;
    for (const entry of readdirSync(root)) {
      const path = join(root, entry, 'package.json');
      if (existsSync(path)) paths.push(path);
    }
  }
  return paths;
}

function main() {
  const base = resolveBase();
  const baseMigrations = git('ls-tree', '--name-only', `${base}:${MIGRATIONS_DIR}`)
    .split('\n')
    .filter((name) => MIGRATION_NAME.test(name));
  const changes = git('diff', '--name-status', '--no-renames', base, 'HEAD', '--', MIGRATIONS_DIR)
    .split('\n')
    .filter(Boolean)
    .map((line) => {
      const [status, path] = line.split('\t');
      return { status: status.charAt(0), path };
    });

  const { errors, warnings, added } = judgeMigrationChanges(changes, baseMigrations);
  // Every migration, not only the new ones: the merged ones all pass, and a clone without the
  // base still cannot slip a generated file through.
  const all = readdirSync(MIGRATIONS_DIR)
    .filter((name) => MIGRATION_NAME.test(name))
    .map((name) => join(MIGRATIONS_DIR, name, 'migration.sql'))
    .filter((path) => existsSync(path));
  for (const path of all) {
    for (const reason of findGeneratedSignals(readFileSync(path, 'utf8'))) {
      errors.push(`${path} looks generated by Prisma: it ${reason}.`);
    }
  }
  for (const path of packageManifests()) {
    errors.push(...findForbiddenScripts(path, JSON.parse(readFileSync(path, 'utf8'))));
  }

  process.stdout.write(
    `Migration safety: base ${base.slice(0, 12)}, ${baseMigrations.length} merged, ` +
      `${added.length} new, ${all.length} checked.\n`,
  );
  for (const warning of warnings) process.stderr.write(`::warning::${warning}\n`);
  if (errors.length > 0) {
    for (const error of errors) process.stderr.write(`::error::${error}\n`);
    process.stderr.write(
      'The SQL migrations are authoritative; see prisma/README.md for how to write one.\n',
    );
    process.exit(1);
  }
  process.stdout.write('No generated or edited migration, and no script that bypasses the SQL.\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
